"""Generate tests/sgp4_vectors.h: reference TEME states from the Python sgp4 package (WGS-72, improved mode) for hand-picked
element sets that exercise every branch of src/sgp4.c. Regenerate with:  python3 scripts/gen_sgp4_test_vectors.py"""
import os, math
from sgp4.api import Satrec, WGS72
# name, mean motion rev/day, ecc, incl deg, raan deg, argp deg, M deg, bstar, times (min)
cases = [
 ("iss_like",        15.5,  0.0006, 51.64, 120.0,  80.0, 280.0, 3.0e-4, [0, 30, 360, 1440, 4320]),
 ("low_perigee_simple", 16.30, 0.002, 97.0,  10.0,  45.0,  10.0, 5.0e-3, [0, 10, 60, 180]),
 ("perigee_lt_98_km", 16.2,  0.012, 65.0,  200.0, 300.0, 100.0, 1.0e-3, [0, 3, 8]),
 ("perigee_lt_156_km", 16.0, 0.0035, 30.0,  50.0,  10.0, 200.0, 2.0e-3, [0, 20, 90]),
 ("eccentric_leo",   10.0,  0.2,    63.4,  300.0, 270.0,  0.0, 1.0e-4, [0, 60, 600, 2880]),
 ("sun_sync",        14.8,  0.001,  98.7,   75.0, 100.0, 330.0, 1.0e-4, [0, 720, 10080]),
 ("polar_retro_i180", 14.0, 0.0005, 180.0,  0.0,   0.0,  45.0, 1.0e-4, [0, 100, 1000]),
 ("equatorial",      13.0,  0.0003, 0.0,    0.0,  90.0,  45.0, 0.0,    [0, 100, 1000]),
 ("zero_bstar_circ", 12.0,  0.00005, 45.0, 123.0,  50.0, 77.0, 0.0,    [0, 300, 4000]),
]
out = ["/* GENERATED by scripts/gen_sgp4_test_vectors.py from the Python sgp4 package; do not edit. */",
       "typedef struct { const char *name; double mm, ecc, inc, raan, argp, ma, bstar; int nt; double t[8], r[8][3], v[8][3]; } Sgp4Case;",
       "static const Sgp4Case SGP4_CASES[] = {"]
for name, mm, e, i, ra, ap, ma, bs, ts in cases:
    s = Satrec(); d = math.pi / 180
    s.sgp4init(WGS72, 'i', 1, 25000.0, bs, 0.0, 0.0, e, ap * d, i * d, ma * d, mm * 2 * math.pi / 1440, ra * d)
    rows = []
    for t in ts:
        err, r, v = s.sgp4_tsince(float(t)); assert err == 0, (name, t, err)
        rows.append((t, r, v))
    ts_s = ", ".join(f"{t:.1f}" for t, _, _ in rows); r_s = ", ".join("{%.12g, %.12g, %.12g}" % r for _, r, _ in rows); v_s = ", ".join("{%.12g, %.12g, %.12g}" % v for _, _, v in rows)
    out.append(f' {{"{name}", {mm!r}, {e!r}, {i!r}, {ra!r}, {ap!r}, {ma!r}, {bs!r}, {len(rows)}, {{{ts_s}}}, {{{r_s}}}, {{{v_s}}}}},')
out.append("};")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "sgp4_vectors.h"), "w").write("\n".join(out) + "\n")
print("wrote", len(cases), "cases")
